"""`run.py publish`: upload results/, the paper and the run logs to the Hugging Face dataset (results/ folder).

Global context: the dataset BurnyCoder/topology-of-neural-geometry holds the pipeline inputs (inputs/, pinned by
configs/base.yaml) and, after every experiment, the results, paper and logs, so the research is inspectable on
the Hub and listed in the project's collection (huggingface_hub HfApi.upload_folder).
"""

from __future__ import annotations

import logging

from huggingface_hub import HfApi

from neurotopo import config

log = logging.getLogger(__name__)


def run() -> None:
    cfg = config.load()
    repo = cfg["hf"]["dataset"]
    api = HfApi()
    root = config.ROOT
    info = api.upload_folder(folder_path=str(root / "results"), path_in_repo="results", repo_id=repo, repo_type="dataset",
                             commit_message="Results of all phases (generated by run.py)")
    api.upload_folder(folder_path=str(root / "logs"), path_in_repo="logs", repo_id=repo, repo_type="dataset",
                      commit_message="Run logs")
    api.upload_file(path_or_fileobj=str(root / "paper" / "main.pdf"), path_in_repo="paper.pdf", repo_id=repo,
                    repo_type="dataset", commit_message="Paper")
    api.upload_file(path_or_fileobj=str(root / "reports" / "summary.md"), path_in_repo="summary.md", repo_id=repo,
                    repo_type="dataset", commit_message="Summary of all experiments")
    try:
        api.add_collection_item(cfg["hf"]["collection"], item_id=repo, item_type="dataset", exists_ok=True)
    except Exception as exc:
        log.warning("collection: %s", exc)
    log.info("published results to %s (commit %s)", repo, info.oid)
